#!/usr/bin/env python3
"""Writes port/platform/ui/gameui_chars.h: the Unicode code point of every
entry of the game's character table (lbl_804E5590 in
src/game/autodata/data_804E549C.c, which lists them as Shift-JIS codes), in
table order. port/platform/ui/gameui.c finds a character's glyph with it,
so that port code can hand over UTF-8 text. Run again when the table in the
source changes; the result is committed."""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = open(os.path.join(ROOT, "src", "game", "autodata", "data_804E549C.c"), encoding="utf-8").read()
body = src[src.index("lbl_804E5590[739]"):]
rows = re.findall(r"\{\s*(\w+),\s*(\w+),\s*\w+,\s*\w+,\s*\w+\s*\}", body)[:739]
assert len(rows) == 739, len(rows)
out = ["/* Generated by port/tools/gen_gameui_chars.py from the game's character",
       " * table; do not edit. Unicode code point per table entry, 0 where the",
       " * entry's code is not a Shift-JIS character. */",
       "static const unsigned short kGameUiChars[739] = {"]
line = []
for i, (card, code) in enumerate(rows):
    assert int(card, 0) == i
    code = int(code, 0)
    raw = bytes([code >> 8, code & 255]) if code > 255 else bytes([code])
    try:
        cp = ord(raw.decode("cp932"))
    except (UnicodeDecodeError, TypeError):
        cp = 0
    line.append("0x%04X" % cp)
    if len(line) == 12 or i == 738:
        out.append("    " + ", ".join(line) + ",")
        line = []
out.append("};")
open(os.path.join(ROOT, "port", "platform", "ui", "gameui_chars.h"), "w").write("\n".join(out) + "\n")
