#!/usr/bin/env python3
"""Make the ASCII glyphs of the port's stand-in for the console's ROM font.

The console takes its system font from the boot ROM, which is not on the
game disc and not in this repository. The game draws a few boot screens
with it (the 60 second wait for the other boards, "PCB ID : n CHECKING...").
This writes port/nogfx/os_font_ascii.inc: the characters 0x20..0x7E as
12x24 cells, 4 bits a pixel, drawn from DejaVu Sans Mono (a free font:
Bitstream Vera licence, embedding and derived bitmaps allowed). The output
is committed; run this only to change the glyphs.

    python3 port/tools/gen_os_font.py [path to DejaVuSansMono.ttf]
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ttf = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
font = ImageFont.truetype(ttf, 18)
rows = []
for c in range(0x20, 0x7F):
    im = Image.new("L", (12, 24), 0)
    ImageDraw.Draw(im).text((6, 20), chr(c), font=font, fill=255, anchor="ms")
    px = im.load()
    for y in range(24):
        v = [px[x, y] >> 4 for x in range(12)]
        rows.append(", ".join("0x%02X" % (v[i] << 4 | v[i + 1]) for i in range(0, 12, 2)))
with open(os.path.join(ROOT, "port", "nogfx", "os_font_ascii.inc"), "w") as f:
    f.write("/* generated by port/tools/gen_os_font.py from DejaVu Sans Mono (Bitstream Vera licence):\n"
            " * characters 0x20..0x7E, 24 rows of 12 pixels each, 4 bits a pixel, high nibble first */\n")
    for i, r in enumerate(rows):
        f.write("  " + r + ("," if i + 1 < len(rows) else "") + ("  /* '%s' */" % chr(0x20 + i // 24).replace("*/", "* /") if i % 24 == 0 and 0x20 + i // 24 != 0x5C else "") + "\n")
